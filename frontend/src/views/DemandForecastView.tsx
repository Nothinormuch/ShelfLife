import React, { useState, useEffect } from 'react';
import { apiFetch } from '../api/client';
import { Product, DemandPrediction, SaleRecord } from '../api/types';
import {
  TrendingUp,
  AlertTriangle,
  Calendar,
  CheckCircle2,
  RefreshCw,
  ServerCrash,
} from 'lucide-react';
import {
  ResponsiveContainer,
  ComposedChart,
  Line,
  Bar,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  Legend,
} from 'recharts';

export const DemandForecastView: React.FC = () => {
  const [products, setProducts] = useState<Product[]>([]);
  const [selectedProductId, setSelectedProductId] = useState<string>('');
  const [prediction, setPrediction] = useState<DemandPrediction | null>(null);
  const [salesHistory, setSalesHistory] = useState<SaleRecord[]>([]);
  const [loading, setLoading] = useState(false);
  const [errorStatus, setErrorStatus] = useState<number | null>(null);

  useEffect(() => {
    apiFetch('/products?pageSize=100')
      .then((res) => res.json())
      .then((data) => {
        if (data.items && data.items.length > 0) {
          setProducts(data.items);
          setSelectedProductId(data.items[0].id);
        }
      })
      .catch((e) => console.error(e));
  }, []);

  const loadForecast = async (productId: string) => {
    if (!productId) return;
    setLoading(true);
    setErrorStatus(null);
    try {
      const [predRes, salesRes] = await Promise.all([
        apiFetch(`/predictions/demand/${productId}`),
        apiFetch(`/sales?productId=${productId}&pageSize=30`),
      ]);

      if (predRes.status === 503 || predRes.status === 502) {
        setErrorStatus(predRes.status);
        setPrediction(null);
      } else if (predRes.ok) {
        const predData = await predRes.json();
        setPrediction(predData);
      }

      if (salesRes.ok) {
        const salesData = await salesRes.json();
        setSalesHistory([...(salesData.items || [])].reverse());
      }
    } catch (e) {
      console.error(e);
      setErrorStatus(503);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (selectedProductId) {
      loadForecast(selectedProductId);
    }
  }, [selectedProductId]);

  const selectedProduct = products.find((p) => p.id === selectedProductId);

  const chartData = salesHistory.map((s) => ({
    date: new Date(s.date).toLocaleDateString(undefined, { month: 'short', day: 'numeric' }),
    actualSales: Number(s.quantitySold),
    predictedDemand: null,
  }));

  if (prediction) {
    chartData.push({
      date: 'Tomorrow (Forecast)',
      actualSales: null as any,
      predictedDemand: Number(prediction.predictedQuantity) as any,
    });
  }

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-slate-900 tracking-tight">Demand Forecast</h1>
          <p className="text-sm text-slate-500">
            Next-day sales demand predictions generated by the machine learning microservice.
          </p>
        </div>

        {/* Product Dropdown Selector */}
        <div className="flex items-center space-x-2">
          <label className="text-xs font-semibold text-slate-600">Product:</label>
          <select
            value={selectedProductId}
            onChange={(e) => setSelectedProductId(e.target.value)}
            className="border border-slate-300 rounded-lg px-3 py-1.5 text-sm font-medium bg-white shadow-xs focus:ring-2 focus:ring-brand-500 focus:outline-hidden"
          >
            {products.map((p) => (
              <option key={p.id} value={p.id}>
                {p.name} ({p.category})
              </option>
            ))}
          </select>
          <button
            onClick={() => loadForecast(selectedProductId)}
            disabled={loading}
            className="p-1.5 border border-slate-200 text-slate-600 hover:bg-slate-100 rounded-lg transition"
            title="Refresh prediction"
          >
            <RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin' : ''}`} />
          </button>
        </div>
      </div>

      {/* ML Service Unavailable State */}
      {errorStatus === 503 && (
        <div className="bg-rose-50 border border-rose-200 rounded-xl p-5 shadow-xs flex items-start space-x-3 text-rose-800">
          <ServerCrash className="w-6 h-6 text-rose-600 shrink-0 mt-0.5" />
          <div>
            <h4 className="font-semibold text-base">Prediction Microservice Unavailable</h4>
            <p className="text-xs text-rose-700 mt-1">
              The Python ML microservice did not respond within the 5-second deadline. The dashboard safely flags this status without affecting store operations.
            </p>
          </div>
        </div>
      )}

      {/* Prediction Cards */}
      {prediction && (
        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          <div className="bg-white border border-slate-200 rounded-xl p-5 shadow-xs">
            <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">
              Expected Demand Tomorrow
            </span>
            <div className="mt-2 flex items-baseline space-x-2">
              <span className="text-3xl font-extrabold text-brand-700">
                {Number(prediction.predictedQuantity).toFixed(1)}
              </span>
              <span className="text-sm text-slate-500 font-medium">
                {selectedProduct?.unit || 'units'}
              </span>
            </div>
            <p className="text-xs text-slate-400 mt-1">
              Horizon: Next Day
            </p>
          </div>

          <div className="bg-white border border-slate-200 rounded-xl p-5 shadow-xs">
            <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">
              Prediction Engine
            </span>
            <div className="mt-2 flex items-center space-x-2">
              <span className="text-lg font-bold text-slate-800 font-mono">
                {prediction.modelVersion}
              </span>
            </div>
            <p className="text-xs text-slate-500 mt-1 flex items-center space-x-1">
              <Calendar className="w-3.5 h-3.5 text-slate-400" />
              <span>Computed: {new Date(prediction.generatedAt).toLocaleTimeString()}</span>
            </p>
          </div>

          <div className="bg-white border border-slate-200 rounded-xl p-5 shadow-xs">
            <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">
              Model Confidence Status
            </span>
            <div className="mt-2">
              {prediction.isFallback ? (
                <div className="inline-flex items-center space-x-1.5 bg-amber-50 text-amber-800 border border-amber-200 px-2.5 py-1 rounded-md text-xs font-bold">
                  <AlertTriangle className="w-3.5 h-3.5 text-amber-600" />
                  <span>Statistical Moving Average ({prediction.fallbackReason})</span>
                </div>
              ) : (
                <div className="inline-flex items-center space-x-1.5 bg-emerald-50 text-emerald-800 border border-emerald-200 px-2.5 py-1 rounded-md text-xs font-bold">
                  <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />
                  <span>Trained ML Model (≥30d sales history)</span>
                </div>
              )}
            </div>
            <p className="text-xs text-slate-400 mt-1">
              {prediction.isFallback
                ? 'Product has limited sales history; estimated via rolling moving average.'
                : 'Random Forest Regressor with day-of-week, lag, and rolling statistics.'}
            </p>
          </div>
        </div>
      )}

      {/* Chart: Actual Sales vs Next-Day Prediction */}
      <div className="bg-white border border-slate-200 rounded-xl p-6 shadow-xs">
        <h3 className="text-base font-semibold text-slate-900 mb-1 flex items-center space-x-2">
          <TrendingUp className="w-5 h-5 text-brand-600" />
          <span>Recent Daily Sales &amp; Next-Day Prediction</span>
        </h3>
        <p className="text-xs text-slate-500 mb-6">
          Daily sales series alongside tomorrow's forecasted demand.
        </p>

        {chartData.length === 0 ? (
          <div className="h-64 flex items-center justify-center text-slate-400 text-sm">
            No sales records available yet. Run the store seeder to populate data.
          </div>
        ) : (
          <div className="h-80 w-full">
            <ResponsiveContainer width="100%" height="100%">
              <ComposedChart data={chartData} margin={{ top: 10, right: 30, left: 0, bottom: 20 }}>
                <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" />
                <XAxis
                  dataKey="date"
                  tick={{ fontSize: 11, fill: '#64748b' }}
                  angle={-25}
                  textAnchor="end"
                  height={50}
                />
                <YAxis tick={{ fontSize: 11, fill: '#64748b' }} />
                <Tooltip
                  contentStyle={{
                    backgroundColor: '#ffffff',
                    borderRadius: '8px',
                    boxShadow: '0 4px 6px -1px rgb(0 0 0 / 0.1)',
                    border: '1px solid #e2e8f0',
                    fontSize: '12px',
                  }}
                />
                <Legend wrapperStyle={{ fontSize: '12px', paddingTop: '10px' }} />
                <Bar
                  dataKey="actualSales"
                  name="Actual Daily Sales"
                  fill="#94a3b8"
                  radius={[4, 4, 0, 0]}
                  maxBarSize={28}
                />
                <Line
                  type="monotone"
                  dataKey="predictedDemand"
                  name="Predicted Next-Day Demand"
                  stroke="#16a34a"
                  strokeWidth={3}
                  dot={{ r: 6, fill: '#16a34a', stroke: '#ffffff', strokeWidth: 2 }}
                />
              </ComposedChart>
            </ResponsiveContainer>
          </div>
        )}
      </div>
    </div>
  );
};
